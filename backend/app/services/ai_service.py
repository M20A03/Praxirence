def is_inaudible_or_non_speech(raw: Optional[str]) -> bool:
    """
    Detects if audio transcription consists solely of silence, non-speech acoustic artifacts
    (e.g., (beep), (static), <noise>, *music*), descriptive sentences ("There is no speech in this audio"),
    timestamps (00:01, 00:00:235), or insufficient dialogue.
    """
    if not raw or not raw.strip():
        return True
    lower = raw.strip().lower()
    exact_inaudible = {
        "00:00", "[audio_silent_or_inaudible]", "[silence]", "[silent]", "[inaudible]",
        "(silence)", "silence", "inaudible", "no speech", "[no speech]", "(beep)", "(static)",
        "(beeping)", "(music)", "[music]", "<music>", "<noise>", "<silence>", "<inaudible>",
        "<cough>", "<coughing>", "<laughter>", "<applause>", "<sigh>", "*beep*", "*music*",
        "*silence*", "*static*", "*cough*", "*applause*", "*sigh*", "(ambient noise)",
        "(background noise)", "(coughing)", "(cough)", "(laughter)", "(sigh)", "(applause)",
        "(typing)", "no speech detected", "[ambient]", "(groan)", "(throat clearing)",
        "thank you for watching", "thanks for watching", "please subscribe",
        "subtitles by", "you", "bye", "bye."
    }
    if lower in exact_inaudible or "[audio_silent_or_inaudible]" in lower or "[silence]" in lower:
        return True

    # Detect descriptive sentences generated by LLMs indicating absence of speech
    for pat in NEGATIVE_SPEECH_PATTERNS:
        if re.search(pat, lower):
            words = set(re.findall(r'[a-zA-Zऀ-ൿ]+', lower))
            if not (words & CLINICAL_WHITELIST_KEYWORDS):
                return True

    # Strip known speaker headers like [Doctor]: [Patient]: Doctor: Patient: Dr: Pt: Clinician:
    cleaned = re.sub(r'(?i)\[?\s*(?:doctor|patient|dr|pt|clinician)\s*\]?\s*:\s*', '', raw)
    # Strip bracketed, parenthesized, angle-bracketed, or asterisked acoustic descriptors
    cleaned = re.sub(r'[\(\[<*][^\)\]>*]*[\)\]>*]', ' ', cleaned).strip()

    # Strip standalone timestamps e.g. 00:01, 00:00:235, 00:00 - 00:05, 01:23
    cleaned = re.sub(r"\b\d{1,2}:\d{2}(?::\d{2})?(?:\.\d+)?\s*(?:-|–|—|to)\s*\d{1,2}:\d{2}(?::\d{2})?(?:\.\d+)?\b", " ", cleaned)
    cleaned = re.sub(r"\b\d{1,2}:\d{2}(?::\d{2})?(?:\.\d+)?\b", " ", cleaned).strip()

    # Check for Indian medical dosage patterns (e.g. 1-0-1, 1-0-0, 0-1-0)
    if re.search(r"\b[012]-[012]-[012](?:-[012])?\b", cleaned):
        return False

    # Require at least one word with 2+ letters (English or Indic regional scripts)
    letters = re.findall(r"[a-zA-Z\u0900-\u0D7F]{2,}", cleaned)
    if not letters:
        return True

    return False


class AIService:
    def __init__(self):
        logger.info("Initializing Praxirence Clinical AI Service...")
        try:
            from ml.inference import model_loader
            self.model_loader = model_loader
        except Exception:
            self.model_loader = None

    def _transcribe_audio_with_gemini(self, audio_path: str, language: Optional[str] = None, api_key: str = "") -> Optional[str]:
        if not audio_path or not os.path.exists(audio_path):
            return None
        if not api_key or len(api_key.strip()) < 15:
            return None
        temp_compressed = None
        try:
            import base64
            prepared_path = audio_path
            ext = os.path.splitext(audio_path)[1].lower()
            mime = "audio/wav" if ext == ".wav" else "audio/mp4" if ext in (".m4a", ".mp4") else "audio/aac" if ext == ".aac" else "audio/mp3" if ext == ".mp3" else "audio/ogg" if ext == ".ogg" else "audio/webm"

            # If audio file is large uncompressed WAV (> 12MB), compress to 64k mono AAC for instant cloud upload
            if os.path.getsize(audio_path) > 12 * 1024 * 1024:
                try:
                    import subprocess
                    temp_compressed = audio_path + ".compressed.m4a"
                    cmd = ["ffmpeg", "-y", "-i", audio_path, "-vn", "-ar", "16000", "-ac", "1", "-b:a", "64k", temp_compressed]
                    subprocess.run(cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, check=False)
                    if os.path.exists(temp_compressed) and os.path.getsize(temp_compressed) > 100:
                        prepared_path = temp_compressed
                        mime = "audio/mp4"
                except Exception as comp_err:
                    logger.warning(f"Audio pre-compression notice: {comp_err}")

            with open(prepared_path, "rb") as f:
                b64_audio = base64.b64encode(f.read()).decode("utf-8")

            payload = {
                "generationConfig": {"temperature": 0.0, "maxOutputTokens": 2048},
                "contents": [{
                    "parts": [
                        {"inlineData": {"mimeType": mime, "data": b64_audio}},
                        {"text": (
                            "You are an exact verbatim medical speech-to-text transcriber for clinical OPD consultations. "
                            "Transcribe ONLY what is audibly spoken in the audio file word-for-word.\n"
                            "CRITICAL ACCURACY & SAFETY RULES:\n"
                            "1. Do NOT invent, hallucinate, assume, or add any dialogue, symptoms, diseases, medications, dosages, or advice not explicitly spoken in the audio.\n"
                            "2. If the audio contains NO human speech, is silent, consists only of background noise, or is unintelligible, respond ONLY with: [AUDIO_SILENT_OR_INAUDIBLE]\n"
                            "3. Retain the exact language spoken (Hinglish, English, Hindi, or regional terms) and label speaker turns as Doctor: and Patient: when distinguishable.\n"
                            "4. Accurately transcribe Indian brand and generic medication names, strengths, and dosages (e.g. Augmentin 625, Dolo 650, Pantocid 40, Telma 40, Azithral 500, Montair LC, 1-0-1, BD, OD, TDS, SOS) exactly as spoken."
                            + (
                                f"\n5. Primary Language: {language.upper()} (accurately preserve regional medical dialogue in {language})."
                                if language and language.lower() not in ("auto", "none", "")
                                else ""
                            )
                        )}
                    ]
                }]
            }
            # Resilient models with multimodal audio support and instant sub-2-second latency
            models = [
                os.environ.get("GEMINI_TRANSCRIPTION_MODEL", "gemini-3.5-flash-lite"),
                "gemini-flash-lite-latest",
                "gemini-3.5-flash",
                "gemini-3.1-flash-lite",
                "gemini-3.8-flash",
            ]
            models = list(dict.fromkeys([m for m in models if m]))
            for m in models:
                url = f"https://generativelanguage.googleapis.com/v1beta/models/{m}:generateContent?key={api_key}"
                try:
                    with httpx.Client(timeout=6.0) as client:
                        res = client.post(url, json=payload, headers={"X-goog-api-key": api_key, "Content-Type": "application/json"})
                        if res.status_code == 200:
                            data = res.json()
                            candidate = data.get("candidates", [{}])[0]
                            content = candidate.get("content", {})
                            parts = content.get("parts", [])
                            if parts and "text" in parts[0]:
                                text = parts[0]["text"].strip()
                                if is_inaudible_or_non_speech(text):
                                    logger.info(f"Gemini ({m}) detected silent, inaudible, or non-speech acoustic audio: {text}")
                                    return "[AUDIO_SILENT_OR_INAUDIBLE]"
                                logger.info(f"Audio consultation successfully transcribed via Gemini ({m})")
                                return text
                            elif candidate.get("finishReason") == "STOP" and not parts:
                                logger.info(f"Gemini ({m}) finished with 0 output tokens (silent audio).")
                                return "[AUDIO_SILENT_OR_INAUDIBLE]"
                except Exception as err:
                    logger.warning(f"Gemini ASR attempt with {m} notice: {err}")
        except Exception as e:
            logger.error(f"Error in _transcribe_audio_with_gemini: {e}")
        finally:
            if temp_compressed and os.path.exists(temp_compressed):
                try:
                    os.remove(temp_compressed)
                except Exception:
                    pass
        return None

    def transcribe_audio(self, audio_path: str, language: Optional[str] = None) -> str:
        """
        True Hybrid ASR Architecture:
        1. When GEMINI_API_KEY is available: Executes Tier 1 Cloud Multimodal ASR for instant
           sub-2-second transcription, verbatim Indian pharmaceutical extraction, and zero server RAM/CPU load.
        2. Seamlessly falls back to Tier 2 In-House Faster-Whisper (int8 CTranslate2) on local CPU
           if offline, rate-limited, or in isolated edge environments.
        3. Guarantees zero downtime, zero OOM risk on low-resource hosts, and instant care plan delivery.
        """
        if os.path.exists(audio_path) and os.path.getsize(audio_path) <= 44:
            logger.info(f"Sub-second / empty audio detected ({os.path.getsize(audio_path)} bytes); returning inaudible token.")
            return "[AUDIO_SILENT_OR_INAUDIBLE]"

        gemini_key = settings.GEMINI_API_KEY or os.environ.get("GEMINI_API_KEY")

        # --- TIER 1: High-Speed Multimodal Cloud ASR (0% CPU, 0MB Server RAM, ~1.5-2.5s) ---
        if gemini_key:
            try:
                cloud_text = self._transcribe_audio_with_gemini(audio_path, language=language, api_key=gemini_key)
                if cloud_text:
                    if is_inaudible_or_non_speech(cloud_text):
                        return "[AUDIO_SILENT_OR_INAUDIBLE]"
                    return cloud_text
            except Exception as e:
                logger.warning(f"Cloud ASR notice ({e}). Failing over to local Faster-Whisper.")

        # --- TIER 2: In-House Local Faster-Whisper (int8 CTranslate2 Base) Failover ---
        if self.model_loader:
            try:
                local_text = self.model_loader.transcribe(audio_path, language=language)
                if local_text and not is_inaudible_or_non_speech(local_text) and local_text != "Doctor: Patient consultation completed. No specific prescription recorded.":
                    logger.info("Audio consultation successfully transcribed via Tier 2 In-House Faster-Whisper.")
                    return local_text
            except Exception as e:
                logger.warning(f"Tier 2 Faster-Whisper notice ({e}).")

        # --- RESILIENT FALLBACK ---
        return "[AUDIO_SILENT_OR_INAUDIBLE]"

    def compress_clinical_dialogue(self, transcript: str, max_words: int = 1600) -> str:
        """
        Clinical dialogue compressor for long-duration consultations (8 to 12+ minutes / 1500+ words).
        Preserves all clinician statements, complaints, vitals, examination findings, medications,
        and red flags while removing conversational filler and repetitive acknowledgments.
        """
        words = transcript.split()
        if len(words) <= max_words:
            return transcript

        lines = transcript.splitlines()
        clinical_lines = []
        for line in lines:
            l_lower = line.lower()
            if any(k in l_lower for k in [
                "doctor:", "dr:", "dr. ", "clinician:", "mg", "mcg", "tablet", "syrup",
                "respule", "drops", "cream", "bp", "pulse", "spo2", "temp", "sugar",
                "pain", "fever", "cough", "chest", "breath", "swelling", "rash",
                "patient:", "pt:", "bukhar", "dard", "khansi", "dawa", "subah", "shaam",
                "days", "din", "daily", "sos", "take", "prescribing", "advice", "report"
            ]):
                clinical_lines.append(line)

        compressed = "\n".join(clinical_lines)
        if len(compressed.split()) >= 120:
            return compressed
        return ' '.join(words[:max_words])

    def diarize_and_denoise_transcript(self, raw_text: str) -> tuple[str, List[Dict[str, Any]]]:
        """
        Parses consultation into cleanly structured [Doctor] and [Patient] turns.
        Supports both inline speaker tokens (e.g. 'Doctor: ... Patient: ...') and continuous un-tagged text.
        Preserves natural turn grouping and avoids spurious speaker flipping.
        """
        if not raw_text or not raw_text.strip() or "[AUDIO_SILENT_OR_INAUDIBLE]" in raw_text:
            return raw_text.strip() if raw_text else "", []

        # If already cleanly diarized with [Doctor]: and [Patient]: turns, preserve directly
        existing_lines = [l.strip() for l in raw_text.splitlines() if l.strip()]
        if existing_lines and all(l.startswith('[Doctor]:') or l.startswith('[Patient]:') for l in existing_lines):
            return raw_text.strip(), []

        diarized_turns: List[str] = []
        amber_alerts: List[Dict[str, Any]] = []

        # Check for explicit speaker labels (inline or line-separated)
        has_speaker_tags = bool(re.search(r'(?i)\b(?:doctor|patient|dr|pt)\b\s*:', raw_text))

        if has_speaker_tags:
            # Normalize brackets and duplicates first
            normalized = re.sub(r'\[\s*(?:doctor|dr)\s*\]\s*:', 'Doctor:', raw_text, flags=re.IGNORECASE)
            normalized = re.sub(r'\[\s*(?:patient|pt)\s*\]\s*:', 'Patient:', normalized, flags=re.IGNORECASE)
            normalized = re.sub(r'\b(?:doctor|dr)\b\s*:\s*(?:doctor|dr)\s*:', 'Doctor:', normalized, flags=re.IGNORECASE)
            normalized = re.sub(r'\b(?:patient|pt)\b\s*:\s*(?:patient|pt)\s*:', 'Patient:', normalized, flags=re.IGNORECASE)

            # Split by inline speaker headers without dropping content
            raw_chunks = re.split(r'(?i)(?=(?:\b(?:doctor|patient|dr|pt)\b\s*:))', normalized)
            current_role = "Doctor"

            for chunk in raw_chunks:
                c = chunk.strip()
                if not c:
                    continue
                doc_match = re.match(r'(?i)^\b(?:doctor|dr)\b\s*:\s*(.*)', c, re.DOTALL)
                pat_match = re.match(r'(?i)^\b(?:patient|pt)\b\s*:\s*(.*)', c, re.DOTALL)

                if doc_match:
                    current_role = "Doctor"
                    content = doc_match.group(1).strip()
                elif pat_match:
                    current_role = "Patient"
                    content = pat_match.group(1).strip()
                else:
                    content = c

                content = re.sub(r'(?i)^(?:\[?\s*(?:doctor|patient|dr|pt)\s*\]?\s*:\s*)+', '', content).strip()
                if content:
                    diarized_turns.append(f"[{current_role}]: {content}")
        else:
            # Continuous speech without speaker tags: Use clinical discourse cues
            sentences = re.split(r'(?<=[.?!])\s+', raw_text)
            current_speaker = "Doctor"
            current_buffer: List[str] = []

            doctor_cues = [
                "kya takleef", "what brings", "since when", "how long", "let me examine",
                "let me check", "open your", "deep breath", "saans lijiye", "blood pressure",
                "temperature", "prescribing", "take this", "tablet", "syrup", "capsule",
                "mg", "1-0-1", "0-1-0", "1-0-0", "after food", "empty stomach", "subah",
                "shaam", "khana", "paracetamol", "augmentin", "pantocid", "azithral",
                "dolo", "telma", "namak kam", "rest kijiye", "come back", "dikhane aana"
            ]

            patient_cues = [
                "i have", "mujhe", "pet mein", "sar mein", "dard", "bukhar", "fever",
                "khansi", "cough", "vomiting", "loose motion", "weakness", "chakkar",
                "do din", "ek hafte", "yesterday", "kal se", "nahi doctor", "yes doctor",
                "haan doctor", "nahi liya", "kabhi nahi", "thank you", "dhanyawad"
            ]

            def detect_role(sent: str) -> Optional[str]:
                s = sent.lower()
                doc_score = sum(1 for cue in doctor_cues if cue in s)
                pat_score = sum(1 for cue in patient_cues if cue in s)
                if doc_score > pat_score and doc_score > 0:
                    return "Doctor"
                if pat_score > doc_score and pat_score > 0:
                    return "Patient"
                return None

            for s in sentences:
                s_clean = s.strip()
                if not s_clean:
                    continue
                detected = detect_role(s_clean)
                if detected and detected != current_speaker:
                    if current_buffer:
                        diarized_turns.append(f"[{current_speaker}]: {' '.join(current_buffer)}")
                        current_buffer = []
                    current_speaker = detected

                current_buffer.append(s_clean)

            if current_buffer:
                diarized_turns.append(f"[{current_speaker}]: {' '.join(current_buffer)}")

        # Merge consecutive turns belonging to the same speaker
        merged_turns: List[str] = []
        for turn in diarized_turns:
            t_clean = turn.strip()
            if not t_clean:
                continue
            match = re.match(r"^\[(Doctor|Patient)\]:\s*(.*)", t_clean, re.DOTALL)
            if match:
                speaker, content = match.group(1), match.group(2).strip()
                if merged_turns and merged_turns[-1].startswith(f"[{speaker}]:"):
                    prev_content = merged_turns[-1][len(f"[{speaker}]: "):].strip()
                    merged_turns[-1] = f"[{speaker}]: {prev_content} {content}".strip()
                else:
                    merged_turns.append(f"[{speaker}]: {content}")
            else:
                merged_turns.append(t_clean)

        diarized_str = "\n".join(merged_turns) if merged_turns else raw_text

        # Common non-drug English & clinical terms that frequently precede numbers in dialogue
        COMMON_NON_DRUGS = {
            "for", "was", "is", "are", "were", "in", "at", "on", "of", "to", "by", "after", "before",
            "every", "per", "take", "taking", "took", "prescribe", "prescribed", "give", "given",
            "days", "day", "weeks", "week", "months", "month", "years", "year", "hours", "hour",
            "mins", "minute", "minutes", "seconds", "times", "time", "daily", "grade", "stage",
            "type", "class", "room", "bed", "ward", "bp", "pulse", "hr", "rr", "spo2", "sugar",
            "glucose", "temp", "temperature", "weight", "height", "bmi", "age", "level", "levels",
            "score", "scores", "rate", "count", "tests", "test", "dose", "doses", "unit", "units",
            "plus", "minus", "about", "around", "approx", "approximately", "nearly", "over", "under",
            "more", "less", "than", "between", "next", "last", "past", "prior", "first", "second",
            "third", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine", "ten",
            "patient", "doctor", "dr", "pt", "he", "she", "his", "her", "him", "they", "them", "their",
            "we", "us", "you", "your", "my", "me", "it", "its", "had", "have", "has", "felt", "feel",
            "feeling", "pain", "fever", "cough", "cold", "headache", "vomiting", "nausea", "stool",
            "stools", "urine", "walk", "sleep", "rest", "work", "routine", "check", "repeat", "visit",
            "appointment", "follow", "up", "since", "from", "into", "through", "during", "then", "now",
            "also", "just", "only", "will", "would", "can", "could", "should", "may", "might", "must",
            "not", "yes", "yeah", "okay", "fine", "good", "bad", "well", "better", "worse", "severe",
            "mild", "moderate", "normal", "high", "low", "lost", "gained", "reading", "readings",
            "tablet", "tablets", "tab", "tabs", "capsule", "capsules", "cap", "caps", "pill", "pills",
            "syrup", "syp", "injection", "inj", "drops", "cream", "gel", "ointment", "inhaler", "respule"
        }

        # Reference list of frequent Indian OPD prescription generics & brands for fuzzy standardization
        COMMON_DRUG_NAMES = [
            "paracetamol", "augmentin", "amoxicillin", "pantoprazole", "pantocid", "azithromycin",
            "azithral", "telmisartan", "telma", "metformin", "glycomet", "amlodipine", "atorvastatin",
            "cetirizine", "montelukast", "ondansetron", "ranitidine", "omeprazole", "ibuprofen",
            "combiflam", "dolo", "calpol", "crocin", "ciprofloxacin", "ofloxacin", "levofloxacin",
            "metronidazole", "flagyl", "cefixime", "zifi", "sumatriptan", "rabeprazole", "rosuvastatin",
            "losartan", "clopidogrel", "glimepiride", "vildagliptin", "linagliptin", "dapagliflozin"
        ]

        ambig_matches = re.finditer(r'\b([a-zA-Z]{3,15})\s+(\d{1,4})\b', raw_text)
        for m in ambig_matches:
            term = m.group(0)
            drug_candidate = m.group(1).lower()
            val = m.group(2)
            if drug_candidate in COMMON_NON_DRUGS or len(drug_candidate) < 4:
                continue

            # Check context: Is it preceded by medication tokens or followed by mg/ml/dose?
            start_pos = max(0, m.start() - 25)
            context_window = raw_text[start_pos:min(len(raw_text), m.end() + 15)].lower()
            has_rx_context = any(rx_kw in context_window for rx_kw in [
                "tab", "tablet", "cap", "capsule", "syp", "syrup", "inj", "dose", "mg", "prescrib",
                "take", "started on", "1-0-1", "0-1-0", "1-0-0", "sos", "bd", "od", "tds"
            ])

            norm = pharmacology_service.normalize_medication(drug_candidate)
            if norm["normalized"]:
                num_val = int(val) if val.isdigit() else 0
                if num_val > 1000 and norm["generic_name"].lower() in ("paracetamol", "dolo", "calpol", "crocin", "augmentin", "amoxicillin"):
                    amber_alerts.append({
                        "term": term,
                        "suggested": f"{norm['generic_name']} {val}mg",
                        "reason": f"High dosage alert: {val}mg single dose exceeds standard OPD threshold. Verify strength.",
                        "confidence": 0.85
                    })
            else:
                close_matches = difflib.get_close_matches(drug_candidate, COMMON_DRUG_NAMES, n=1, cutoff=0.72)
                if close_matches:
                    amber_alerts.append({
                        "term": term,
                        "suggested": f"{close_matches[0].title()} {val}mg",
                        "reason": f"Phonetically ambiguous drug candidate matching '{close_matches[0].title()}'. Verify dosage and spelling.",
                        "confidence": 0.82
                    })
                elif has_rx_context:
                    amber_alerts.append({
                        "term": term,
                        "suggested": f"{drug_candidate.title()} {val}mg",
                        "reason": "Uncataloged medication candidate in prescription context. Clinician verification recommended.",
                        "confidence": 0.70
                    })

        return diarized_str, amber_alerts

    def extract_vitals_from_dialogue(self, text: str) -> Dict[str, Any]:
        """
        Extracts physiological vitals mentioned during consultation.
        """
        vitals: Dict[str, Any] = {}

        # Blood pressure
        bp_match = re.search(r'\b(?:bp|blood\s*pressure)\s*(?:is|was|of)?\s*(\d{2,3}\s*/\s*\d{2,3})\b', text, re.IGNORECASE)
        if bp_match:
            vitals["bp"] = bp_match.group(1).replace(" ", "")

        # Pulse / Heart rate
        pulse_match = re.search(r'\b(?:pulse|heart\s*rate|pr|hr)\s*(?:is|of|was)?\s*(\d{2,3})\s*(?:bpm)?\b', text, re.IGNORECASE)
        if pulse_match:
            vitals["pulse"] = f"{pulse_match.group(1)} bpm"

        # SpO2
        spo2_match = re.search(r'\b(?:spo2|oxygen|saturation)\s*(?:is|of|was)?\s*(\d{2,3})\s*%', text, re.IGNORECASE)
        if spo2_match:
            vitals["spo2"] = f"{spo2_match.group(1)}%"

        # Temperature
        temp_match = re.search(r'\b(?:temp|temperature|fever)\s*(?:is|of|was)?\s*(\d{2,3}(?:\.\d)?)\s*(?:°?f|f|degrees)?\b', text, re.IGNORECASE)
        if temp_match:
            vitals["temperature"] = f"{temp_match.group(1)} °F"

        # Blood sugar
        sugar_match = re.search(r'\b(?:sugar|glucose|rbs|fbs|ppbs)\s*(?:is|of|was)?\s*(\d{2,3})\s*(?:mg/dl)?\b', text, re.IGNORECASE)
        if sugar_match:
            vitals["blood_sugar"] = f"{sugar_match.group(1)} mg/dL"

        # Weight
        wt_match = re.search(r'\b(?:weight|wt)\s*(?:is|of|was)?\s*(\d{2,3}(?:\.\d)?)\s*(?:kg|kgs)\b', text, re.IGNORECASE)
        if wt_match:
            vitals["weight"] = f"{wt_match.group(1)} kg"

        return vitals

    @classmethod
    def _get_icd_mappings(cls) -> list:
        if not hasattr(cls, "_icd_cache"):
            import json
            from pathlib import Path
            json_path = Path(__file__).resolve().parent.parent.parent / "data" / "icd10_mappings.json"
            if json_path.exists():
                with open(json_path, "r", encoding="utf-8") as f:
                    cls._icd_cache = json.load(f)
            else:
                cls._icd_cache = []
        return cls._icd_cache

    def map_icd10_diagnosis(self, raw_diagnosis: str) -> Dict[str, str]:
        """
        Maps clinical diagnostic terminology to standard ICD-10 codes.
        """
        diag_lower = raw_diagnosis.lower()

        icd_rules = self._get_icd_mappings()
        for item in icd_rules:
            if item.get("keyword") in diag_lower:
                code = item.get("code")
                title = item.get("title")
                return {"code": code, "title": title, "display": f"{title} (ICD-10: {code})"}

        return {"code": "R69", "title": raw_diagnosis.strip(), "display": f"{raw_diagnosis.strip()} (ICD-10: R69)"}

